"""Regenerate Paintbooth's documentation from the source code.

Run it after every change, before committing (CI checks that the generated files are current)::

    python tools/gen_docs.py            # write docs/
    python tools/gen_docs.py --check    # exit 1 if docs/ is out of date (used by CI)

It writes three things:

* ``docs/api/``: a searchable HTML API reference, built with pdoc from the docstrings. Open
  ``docs/api/index.html`` in a browser; the search box covers every module, class and function.
  This step needs ``pdoc`` and a Python with tkinter (the GUI modules import it), and is skipped with a
  note when either is missing.
* ``docs/reference/modules.md``: every module with its purpose (the first docstring paragraph).
* ``docs/reference/build-actions.md``: every Mods Studio 2 build action the template engine supports,
  taken from the ``Engine.a_*`` docstrings.

The hand-written pages (``docs/README.md``, ``architecture.md`` and so on) are not touched.
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "paintbooth"
DOCS = ROOT / "docs"
HEADER = "<!-- Generated by tools/gen_docs.py from the source code. Do not edit by hand. -->\n\n"


def _first_paragraph(doc: str | None) -> str:
    """The first paragraph of a docstring, joined onto one line ("" when there is none)."""
    if not doc:
        return ""
    para = doc.strip().split("\n\n", 1)[0]
    return " ".join(line.strip() for line in para.splitlines())


def _modules() -> list[tuple[str, Path]]:
    """All modules of the package as ``(dotted name, path)``, sorted with packages first."""
    out = []
    for p in sorted(PKG.rglob("*.py")):
        if "__pycache__" in p.parts:
            continue
        rel = p.relative_to(ROOT).with_suffix("")
        parts = list(rel.parts)
        if parts[-1] == "__init__":
            parts.pop()
        out.append((".".join(parts), p))
    return out


def modules_md() -> str:
    """Build ``docs/reference/modules.md``: one table row per module."""
    rows = [
        "# Module reference",
        "",
        "Every module in the `paintbooth` package, with its purpose.",
        "The full API of each one is in the [HTML reference](../api/index.html).",
        "",
        "| Module | Purpose |",
        "|---|---|",
    ]
    for name, path in _modules():
        src = path.read_text(encoding="utf-8")
        doc = _first_paragraph(ast.get_docstring(ast.parse(src)))
        cell = doc.replace("|", "\\|")  # a | would end the Markdown table cell
        rows.append(f"| `{name}` | {cell} |")
    return HEADER + "\n".join(rows) + "\n"


def build_actions_md() -> str:
    """Build ``docs/reference/build-actions.md`` from the template engine's action table and docstrings."""
    tree = ast.parse((PKG / "ms2tpl.py").read_text(encoding="utf-8"))
    table: dict[str, str] = {}
    methods: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "_ACTIONS" for t in node.targets
        ):
            table = ast.literal_eval(node.value)
        if isinstance(node, ast.FunctionDef) and node.name.startswith("a_"):
            methods[node.name] = ast.get_docstring(node) or "(not documented)"
    lines = [
        "# Mods Studio 2 build actions",
        "",
        "A Mods Studio 2 template (`template.xml`) describes an export as a list of *build actions*.",
        "Paintbooth's template engine (`paintbooth/ms2tpl.py`, class `Engine`) runs them in order to",
        "produce the files of the mod. These are all the actions it supports. `{{Name}}` in any text is",
        "replaced by the value of the variable `Name` (`{{A.B}}` is a child variable, `{{X:D2}}` pads",
        "a number to two digits). Unknown variables are left as they are, as Mods Studio 2 does.",
        "",
        "All paths are relative to the mod root, and every path is checked: an action can't read or",
        "write outside the Mods Studio 2 template folder or the mod (see `paintbooth/safepath.py`).",
        "",
    ]
    for kind, meth in table.items():
        lines += [f"## {kind}", "", f"Runs `Engine.{meth}`.", "", methods.get(meth, "(missing)"), ""]
    return HEADER + "\n".join(lines)


def build_api(out: Path) -> str | None:
    """Run pdoc into ``out``; return a reason string when it can't run here, else None."""
    if importlib.util.find_spec("pdoc") is None:
        return "pdoc is not installed (pip install pdoc)"
    if importlib.util.find_spec("tkinter") is None:
        return "this Python has no tkinter, which the GUI modules need"
    cmd = [
        sys.executable,
        "-m",
        "pdoc",
        "--docformat",
        "google",
        "--no-show-source",
        "-o",
        str(out),
        "paintbooth",
    ]
    subprocess.run(cmd, check=True, cwd=ROOT)
    return None


def _same_tree(a: Path, b: Path) -> bool:
    """True when two folders hold the same files with the same bytes."""
    fa = {p.relative_to(a): p.read_bytes() for p in a.rglob("*") if p.is_file()}
    fb = {p.relative_to(b): p.read_bytes() for p in b.rglob("*") if p.is_file()}
    return fa == fb


def main(argv: list[str] | None = None) -> int:
    """Write (or with ``--check`` compare) the generated documentation; return the exit code."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("--check", action="store_true", help="only report whether docs/ is up to date")
    ap.add_argument("--no-api", action="store_true", help="skip the pdoc HTML reference")
    a = ap.parse_args(argv)

    generated = {
        DOCS / "reference" / "modules.md": modules_md(),
        DOCS / "reference" / "build-actions.md": build_actions_md(),
    }
    stale = [p for p, text in generated.items() if not p.exists() or p.read_text(encoding="utf-8") != text]

    if not a.no_api:
        with tempfile.TemporaryDirectory() as tmp:
            why = build_api(Path(tmp))
            if why:
                print(f"skipped the HTML API reference: {why}")
            elif a.check:
                if not (DOCS / "api").is_dir() or not _same_tree(Path(tmp), DOCS / "api"):
                    stale.append(DOCS / "api")
            else:
                shutil.rmtree(DOCS / "api", ignore_errors=True)
                shutil.copytree(tmp, DOCS / "api")

    if a.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run python tools/gen_docs.py)")
        return 1 if stale else 0
    for p, text in generated.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(generated)} reference pages" + ("" if a.no_api else " and docs/api/"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
